import fs from 'node:fs';
import path from 'node:path';

const distRoot = path.join(process.cwd(), 'dist');
const entryFile = path.join(distRoot, 'renderer', 'app.js');
const moduleFiles = new Map();

function toModuleId(filePath) {
  return path.relative(distRoot, filePath).replace(/\\/g, '/').replace(/\.js$/i, '');
}

function resolveLocalRequire(fromFile, request) {
  if (!request.startsWith('.')) {
    throw new Error(`Renderer bundle refused non-local require "${request}" from ${toModuleId(fromFile)}. Keep renderer code browser-safe.`);
  }
  const base = path.resolve(path.dirname(fromFile), request);
  const candidates = request.endsWith('.js') ? [base] : [base + '.js', path.join(base, 'index.js')];
  const resolved = candidates.find((candidate) => fs.existsSync(candidate));
  if (!resolved) {
    throw new Error(`Renderer bundle could not resolve "${request}" from ${toModuleId(fromFile)}.`);
  }
  if (!resolved.startsWith(distRoot + path.sep)) {
    throw new Error(`Renderer bundle refused require outside dist: ${request}`);
  }
  return resolved;
}

function collect(filePath) {
  const normalized = path.normalize(filePath);
  const id = toModuleId(normalized);
  if (moduleFiles.has(id)) return;
  const source = fs.readFileSync(normalized, 'utf8');
  const requires = [...source.matchAll(/require\((['"])([^'"]+)\1\)/g)].map((match) => match[2]);
  const localRequires = requires.filter((request) => request.startsWith('.'));
  for (const request of localRequires) collect(resolveLocalRequire(normalized, request));
  const transformed = source.replace(/require\((['"])([^'"]+)\1\)/g, (_match, _quote, request) => {
    if (!request.startsWith('.')) {
      throw new Error(`Renderer bundle refused non-local require "${request}" from ${id}.`);
    }
    return `__require(${JSON.stringify(toModuleId(resolveLocalRequire(normalized, request)))})`;
  });
  moduleFiles.set(id, transformed);
}

if (!fs.existsSync(entryFile)) {
  throw new Error(`Renderer entry missing: ${entryFile}. Run tsc before renderer bundling.`);
}

collect(entryFile);

const modules = [...moduleFiles.entries()].map(([id, code]) => {
  return `__modules[${JSON.stringify(id)}] = function(__require, exports, module) {\n${code}\n};`;
}).join('\n\n');

const bundle = `// Generated by scripts/bundle-renderer-cjs.mjs during npm run build.\n// Keeps the renderer browser-safe with nodeIntegration=false by bundling local CommonJS modules.\n(function () {\n  \"use strict\";\n  const __modules = Object.create(null);\n  const __cache = Object.create(null);\n\n${modules}\n\n  function __require(id) {\n    if (__cache[id]) return __cache[id].exports;\n    const factory = __modules[id];\n    if (!factory) throw new Error(\"Renderer module not bundled: \" + id);\n    const module = { exports: {} };\n    __cache[id] = module;\n    factory(__require, module.exports, module);\n    return module.exports;\n  }\n\n  __require(\"renderer/app\");\n})();\n`;

fs.writeFileSync(entryFile, bundle, 'utf8');
console.log(`BUNDLED_RENDERER_APP=1 modules=${moduleFiles.size}`);
